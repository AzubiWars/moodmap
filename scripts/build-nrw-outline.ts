/**
 * Derives the NRW outline for the app logo (#91) from public/geo/nrw-regbez.geojson (© BKG, dl-de/by-2-0):
 *   1. dissolve the 5 Regierungsbezirke (shared edges cancel out, only the outer border stays)
 *   2. project with a latitude correction (cos 51.45°), so NRW is not stretched
 *   3. simplify (Douglas-Peucker) and fit into a 100 × 100 box
 * Output: src/components/brand/nrwOutline.ts (committed)
 *
 * Usage: node scripts/build-nrw-outline.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

type Pt = [number, number];
const root = fileURLToPath(new URL('..', import.meta.url));
const TOLERANCE = 0.9; // in box units (box = 100)

const geo = JSON.parse(readFileSync(`${root}public/geo/nrw-regbez.geojson`, 'utf8'));

const rings: Pt[][] = [];
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) rings.push(poly[0]);
}

// Dissolve: an edge that appears in both directions is internal.
const key = (p: Pt) => `${p[0]},${p[1]}`;
const edges = new Map<string, { a: Pt; b: Pt }>();
for (const ring of rings) {
  for (let i = 0; i < ring.length - 1; i++) {
    const a = ring[i] as Pt;
    const b = ring[i + 1] as Pt;
    const rev = `${key(b)}>${key(a)}`;
    if (edges.has(rev)) edges.delete(rev);
    else edges.set(`${key(a)}>${key(b)}`, { a, b });
  }
}

// Chain the remaining edges into closed rings, keep the longest (drops enclaves).
const next = new Map<string, Pt[]>();
for (const { a, b } of edges.values()) next.set(key(a), [...(next.get(key(a)) ?? []), b]);
const used = new Set<string>();
let best: Pt[] = [];
for (const { a } of edges.values()) {
  if (used.has(key(a))) continue;
  const ring: Pt[] = [a];
  let cur = a;
  for (;;) {
    used.add(key(cur));
    const cand = (next.get(key(cur)) ?? []).find((p) => !used.has(key(p)) || key(p) === key(a));
    if (!cand || key(cand) === key(a)) break;
    ring.push(cand);
    cur = cand;
  }
  if (ring.length > best.length) best = ring;
}
if (best.length < 50) throw new Error(`dissolve failed (ring has ${best.length} points)`);

const cosLat = Math.cos((51.45 * Math.PI) / 180);
const proj = best.map(([lon, lat]): Pt => [lon * cosLat, -lat]);
const xs = proj.map((p) => p[0]);
const ys = proj.map((p) => p[1]);
const minX = Math.min(...xs);
const minY = Math.min(...ys);
const scale = 100 / Math.max(Math.max(...xs) - minX, Math.max(...ys) - minY);
const w = (Math.max(...xs) - minX) * scale;
const h = (Math.max(...ys) - minY) * scale;
const pts = proj.map(([x, y]): Pt => [
  (x - minX) * scale + (100 - w) / 2,
  (y - minY) * scale + (100 - h) / 2,
]);

function rdp(p: Pt[], eps: number): Pt[] {
  const a = p[0] as Pt;
  const b = p[p.length - 1] as Pt;
  let max = 0;
  let idx = 0;
  for (let i = 1; i < p.length - 1; i++) {
    const q = p[i] as Pt;
    const d =
      Math.abs((b[0] - a[0]) * (a[1] - q[1]) - (a[0] - q[0]) * (b[1] - a[1])) /
      (Math.hypot(b[0] - a[0], b[1] - a[1]) || 1);
    if (d > max) [max, idx] = [d, i];
  }
  if (max <= eps) return [a, b];
  return [...rdp(p.slice(0, idx + 1), eps).slice(0, -1), ...rdp(p.slice(idx), eps)];
}
// Split the closed ring in two halves so it simplifies evenly.
const half = Math.floor(pts.length / 2);
const simple = [
  ...rdp(pts.slice(0, half + 1), TOLERANCE).slice(0, -1),
  ...rdp([...pts.slice(half), pts[0] as Pt], TOLERANCE).slice(0, -1),
];

const f = (n: number) => String(Math.round(n * 10) / 10);
const d = `M${simple.map(([x, y]) => `${f(x)} ${f(y)}`).join('L')}Z`;
mkdirSync(`${root}src/components/brand`, { recursive: true });
writeFileSync(
  `${root}src/components/brand/nrwOutline.ts`,
  `// Generated by scripts/build-nrw-outline.ts from public/geo/nrw-regbez.geojson (© BKG, dl-de/by-2-0). Do not edit.\n// Box: 0 0 100 100, ${simple.length} points.\nexport const NRW_OUTLINE_PATH =\n  '${d}';\n`,
);
console.log(`${best.length} -> ${simple.length} points`);
