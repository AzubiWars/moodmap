/**
 * Builds supabase/seed.sql (#93): master data + survey config from the sources in the repo.
 * Upserts, so it can be re-applied to an existing database when the sources change.
 * Synthetic answers are not part of this seed (#8, #23).
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { QUESTIONS, TOPICS } from '../../src/data/topics.ts';
import type { DirectorySchool, Question, School, Topic } from '../../src/types/domain.ts';
import type { KreisCollection } from './geo.ts';
import { waveRange, type WaveSpec } from './waves.ts';

/** School year 2026/27: from the start of the answer seed history (#8) to the summer holidays. */
export const SEED_WAVES = { first: '2026-W34', last: '2027-W30' } as const;

export interface SeedSources<S extends School | DirectorySchool = School | DirectorySchool> {
  regbez: { type: 'FeatureCollection'; features: { properties: { id: string; name: string } }[] };
  kreise: KreisCollection;
  /** Synthetic fixtures carry demo join codes; the real directory never does (#257). */
  schools: readonly S[];
  topics: readonly Topic[];
  questions: readonly Question[];
  waves: readonly WaveSpec[];
}

const repoPath = (relative: string) => fileURLToPath(new URL(`../../${relative}`, import.meta.url));
const readJson = <T>(relative: string) => JSON.parse(readFileSync(repoPath(relative), 'utf8')) as T;

/** Synthetic fixtures (with demo join codes) for tests; the real directory for production seeding. */
export function loadSeedSources(options: { synthetic: true }): SeedSources<School>;
export function loadSeedSources(options?: { synthetic?: boolean }): SeedSources;
export function loadSeedSources(options: { synthetic?: boolean } = {}): SeedSources {
  return {
    regbez: readJson('public/geo/nrw-regbez.geojson'),
    kreise: readJson('public/geo/nrw-kreise.geojson'),
    // Produktions-Stammdaten sind die echten NRW-Schulstandorte; synthetisch nur für die Test-Fixtures.
    schools: readJson(options.synthetic ? 'public/data/schools.json' : 'public/data/schools.real.json'),
    topics: TOPICS,
    questions: QUESTIONS,
    waves: waveRange(SEED_WAVES.first, SEED_WAVES.last),
  };
}

type SqlValue = string | number | boolean | null | undefined | readonly string[] | { json: unknown };

/** SQL literal. Inputs are our own repo data, but quoting is still done properly. */
export function sqlLiteral(value: SqlValue): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`Not a finite number: ${value}`);
    return String(value);
  }
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'string') return `'${value.replaceAll("'", "''")}'`;
  if ('json' in value) return `${sqlLiteral(JSON.stringify(value.json))}::jsonb`;
  return `array[${value.map((v) => sqlLiteral(v)).join(', ')}]::text[]`;
}

function upsert(table: string, columns: string[], key: string[], rows: SqlValue[][]): string {
  const updates = columns.filter((c) => !key.includes(c)).map((c) => `${c} = excluded.${c}`);
  return [
    `insert into public.${table} (${columns.join(', ')}) values`,
    rows.map((row) => `  (${row.map(sqlLiteral).join(', ')})`).join(',\n'),
    `on conflict (${key.join(', ')}) do ${updates.length ? `update set ${updates.join(', ')}` : 'nothing'};`,
  ].join('\n');
}

/**
 * Real schools get no join code from the repo: the column default (`public.new_join_code()`) draws a
 * random one on first insert, and re-seeding never overwrites it (#257). Only synthetic fixtures
 * (demo codes like DEMO42) write their codes.
 */
function schoolsUpsert(schools: SeedSources['schools']): string {
  const columns = ['id', 'name', 'school_form', 'kreis_id', 'city', 'lat', 'lon', 'student_count'];
  const withCodes = schools.every((s) => 'joinCode' in s && s.joinCode);
  return upsert(
    'schools',
    withCodes ? [...columns, 'join_code'] : columns,
    ['id'],
    schools.map((s) => {
      const row: SqlValue[] = [s.id, s.name, s.schoolForm, s.kreisId, s.city, s.lat, s.lon, s.studentCount];
      return withCodes ? [...row, (s as School).joinCode] : row;
    }),
  );
}

export function buildSeedSql(sources: SeedSources): string {
  const sections = [
    [
      '-- Generated by `npm run db:seed:build` (scripts/generate-supabase-seed.ts) – do not edit by hand.',
      '-- Master data + survey config for local `supabase db reset` and the hosted project (#93).',
    ].join('\n'),
    upsert(
      'regbez',
      ['id', 'name'],
      ['id'],
      sources.regbez.features.map(({ properties: p }) => [p.id, p.name]),
    ),
    upsert(
      'kreise',
      ['id', 'name', 'regbez_id', 'type'],
      ['id'],
      sources.kreise.features.map(({ properties: p }) => [p.id, p.name, p.regbez_id, p.type]),
    ),
    schoolsUpsert(sources.schools),
    upsert(
      'topics',
      ['slug', 'title', 'icon', 'audience', 'mandatory', 'sort', 'priority'],
      ['slug'],
      sources.topics.map((t) => [t.slug, t.title, t.icon, t.audience, t.mandatory, t.sort, t.priority]),
    ),
    upsert(
      'questions',
      ['id', 'topic_slug', 'type', 'text', 'options', 'multiple', 'invert', 'weight', 'audience'],
      ['id'],
      sources.questions.map((q) => [
        q.id,
        q.topicSlug,
        q.type,
        q.text,
        q.options ? { json: q.options } : null,
        q.multiple ?? false,
        q.invert ?? false,
        q.weight,
        q.audience,
      ]),
    ),
    upsert(
      'waves',
      ['id', 'starts_at', 'ends_at'],
      ['id'],
      sources.waves.map((w) => [
        w.id,
        `${w.monday} 00:00 Europe/Berlin`,
        `${w.nextMonday} 00:00 Europe/Berlin`,
      ]),
    ),
  ];
  return `${sections.join('\n\n')}\n`;
}
